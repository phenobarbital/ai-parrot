# §11 Initialization Workflow
# ---------------------------------------------------------------------------


async def initialize_vault(toolkit: ObsidianToolkit) -> list[str]:
    """§11 — create missing generated control/index files, idempotently.

    Never overwrites existing content (§11 step 4) and never touches
    ``Private/``/``.obsidian/`` (§11 steps 2/6). Creates no project,
    entity, concept, or source pages (§11 step 5).

    Args:
        toolkit: This subsystem's own :class:`ObsidianToolkit`.

    Returns:
        The vault-relative paths actually created this call (empty on a
        fully-initialized vault — idempotent).
    """
    created: list[str] = []
    for path in _CONTROL_FILES:
        if await _create_if_missing(toolkit, path, _DEFAULT_BODIES[path]):
            created.append(path)
    for path in _FOLDER_INDEXES:
        if await _create_if_missing(toolkit, path, _FOLDER_INDEX_TITLES[path]):
            created.append(path)
    return created


async def _create_if_missing(toolkit: ObsidianToolkit, path: str, body: str) -> bool:
    """Create ``path`` with ``body`` only if it does not already exist.

    Args:
        toolkit: This subsystem's own :class:`ObsidianToolkit`.
        path: Vault-relative path.
        body: Markdown body for a freshly created file.

    Returns:
        ``True`` if the file was created, ``False`` if it already existed.
    """
    try:
        await toolkit.read_note(path, include_content=False)
        return False
    except FileNotFoundError:
        await toolkit.create_note(path, body)
        return True


# ---------------------------------------------------------------------------
# §8.1 link-fixup — move_note() reports affected_backlinks but does not
# rewrite them.
# ---------------------------------------------------------------------------


async def fixup_links(
    toolkit: ObsidianToolkit,
    *,
    old_path: str,
    new_path: str,
    affected_backlinks: list[str],
) -> list[str]:
    """Rewrite ``[[wikilinks]]`` in every backlinking note after a move.

    ``ObsidianToolkit.move_note`` reports ``affected_backlinks`` (notes
    whose wikilinks referenced the old path/name) but does NOT rewrite
    them — this is the new §8.1 helper the spec calls for. Matches
    Obsidian's own resolution semantics (exact normalized path, else
    basename), so both ``[[Old Path/Old Name]]`` and ``[[Old Name]]``
    forms are rewritten.

    Args:
        toolkit: This subsystem's own :class:`ObsidianToolkit`.
        old_path: The note's vault-relative path before the move.
        new_path: The note's vault-relative path after the move.
        affected_backlinks: The ``affected_backlinks`` list
            ``move_note`` returned.

    Returns:
        The vault-relative paths actually rewritten (a subset of
        ``affected_backlinks`` — a backlink that no longer matches after
        re-reading is left untouched).
    """
    old_norm = _norm_target(old_path)
    old_stem = _basename(old_norm).lower()
    new_norm = _norm_target(new_path)

    def _sub(match: re.Match[str]) -> str:
        target = match.group(2).strip()
        norm_target = _norm_target(target)
        if norm_target == old_norm or norm_target.lower() == old_stem:
            return f"{match.group(1)}{new_norm}{match.group(3)}"
        return match.group(0)

    rewritten: list[str] = []
    for backlink_path in affected_backlinks:
        raw = await toolkit.vault.read_note(backlink_path)
        new_text, count = _WIKILINK_RE.subn(_sub, raw)
        if count:
            await toolkit.vault.write_note(backlink_path, new_text, overwrite=True)
            rewritten.append(backlink_path)
    return rewritten


def _norm_target(target: str) -> str:
    """Normalize a wikilink target the same way the vault index does."""
    text = target.strip()
    if text.lower().endswith(".md"):
        text = text[: -len(".md")]
    return text


def _basename(path: str) -> str:
    """POSIX basename without importing posixpath at call sites."""
    return path.rsplit("/", 1)[-1]


# ---------------------------------------------------------------------------
# §25 Processed Source Registry mirror — regenerated from the DB every
# ingest (R1). The DB (MeetingRegistry) is the authority; this mirror is
# derived-only and must never gate a fetch/skip decision.
# ---------------------------------------------------------------------------


async def regenerate_registry_mirror(toolkit: ObsidianToolkit, registry: MeetingRegistry) -> str:
    """Regenerate ``Wiki/Registry/processed-sources.md`` from the DB.

    Overwrite-regenerates the whole file every call — never hand-edited,
    so there is nothing to preserve (§25).

    Args:
        toolkit: This subsystem's own :class:`ObsidianToolkit`.
        registry: The :class:`MeetingRegistry` to mirror. Expects
            ``record.note_path`` to already hold this subsystem's own
            canonical ``Wiki/Sources/Meetings/...`` page path — set by
            the orchestrator's ``record_synced()`` call (spec Module 6)
            after the meeting-page renderer (Module 8) writes the page.

    Returns:
        The rendered Markdown body that was written.
    """
    records = await registry.all_records()
    lines = [
        "# Processed Source Registry",
        "",
        (
            "Derived, human-readable mirror of the MeetingRegistry (`wiki.db`, "
            "FEAT-472) — see contract §25. Regenerated every ingest; never "
            "hand-edit."
        ),
        "",
    ]
    for record in sorted(records, key=lambda r: r.meeting_date):
        page_link = f"Wiki/Sources/Meetings/{Path(record.note_path).stem}"
        lines.append(
            f"- `{record.external_id}` | meeting `{record.meeting_date}` | "
            f"summary `{record.summary_fingerprint or 'unknown'}` | "
            f"transcript `{record.fingerprint or 'unknown'}` | "
            f"[[{page_link}|Source Page]] | processed `{record.synced_at}`"
        )
    body = "\n".join(lines) + "\n"

    path = "Wiki/Registry/processed-sources.md"
    try:
        await toolkit.read_note(path, include_content=False)
        await toolkit.update_note(path, body, preserve_frontmatter=False)
    except FileNotFoundError:
        await toolkit.create_note(path, body)
    return body
