"""Vault access layer — own toolkit, §11 init, §25 mirror, §8.1 link-fixup
(FEAT-481, spec Module 4).

**Additive-only (G11).** This module instantiates its **own**
``ObsidianToolkit`` (constructor arg — no edit to ``tools/obsidian.py``)
and never modifies FEAT-472's ``MeetingRegistry``. All vault writes made
by this subsystem go through :func:`build_vault_toolkit`'s instance.

**Registry location convention.** Neither ``sdd/specs/
fireflies-wiki-knowledgebase-agent.spec.md`` Module 1 nor this module's
own file list adds a new ``conf.py`` key for the registry directory (M2
fetch-gate and this module are independent, parallel tasks — spec
Worktree Strategy). Both derive the same directory purely from
:data:`~parrot.flows.wiki_ingest.conf.WIKI_KB_VAULT_PATH`:
``<vault>/Wiki/Registry`` (see :func:`registry_dir_for_vault`) — the same
folder the contract's §25 mirror file already lives in, so the
``MeetingRegistry``'s ``wiki.db`` and its human-readable mirror are
colocated. This mirrors FEAT-472's own ``FIREFLIES_REGISTRY_DIR`` default
(the wiki storage dir) without redefining it.
"""

