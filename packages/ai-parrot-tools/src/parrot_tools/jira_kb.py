"""Jira site knowledge base — YAML-backed structural cache (FEAT-696 M6)."""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Optional, Union

import yaml
from pydantic import BaseModel, ConfigDict, Field

logger = logging.getLogger(__name__)


class IssueTypeEntry(BaseModel):
    """One issue type inside a project."""

    id: str
    subtask: bool = False
    level: int = 0


class ProjectEntry(BaseModel):
    """Project with its issue-type map."""

    name: str
    issue_types: dict[str, IssueTypeEntry] = Field(default_factory=dict)


class PrioritiesEntry(BaseModel):
    """Priority scale plus legacy names."""

    scale: list[str] = Field(default_factory=list)
    legacy: list[str] = Field(default_factory=list)
    default: Optional[str] = None


class LimitsEntry(BaseModel):
    """Field length limits enforced before API calls."""

    description_max_chars: Optional[int] = None
    summary_max_chars: Optional[int] = None
    summary_target_chars: Optional[int] = None


class TemplateEntry(BaseModel):
    """Template to allowed issue types mapping."""

    types: list[str]
    default: str


class JiraKnowledgeBase(BaseModel):
    """Jira site structural cache loaded from a YAML file."""

    model_config = ConfigDict(extra="allow")

    site: str
    cloud_id: Optional[str] = None
    verified: Optional[str] = None
    projects: dict[str, ProjectEntry] = Field(default_factory=dict)
    priorities: PrioritiesEntry = Field(default_factory=PrioritiesEntry)
    status_map: dict[str, list[str]] = Field(default_factory=dict)
    fields: dict[str, str] = Field(default_factory=dict)
    limits: LimitsEntry = Field(default_factory=LimitsEntry)
    templates: dict[str, TemplateEntry] = Field(default_factory=dict)
    components: list[str] = Field(default_factory=list)

    @classmethod
    def load(cls, path: Union[str, Path]) -> "JiraKnowledgeBase":
        """Load a KB from a YAML file.

        Args:
            path: Path to the YAML file.

        Returns:
            The parsed knowledge base.

        Raises:
            ValueError: If the file is not a YAML mapping.
        """
        p = Path(path)
        with p.open("r", encoding="utf-8") as fh:
            data = yaml.safe_load(fh)
        if not isinstance(data, dict):
            raise ValueError(f"KB file {p} does not contain a YAML mapping")
        return cls.model_validate(data)

    def save(self, path: Union[str, Path]) -> None:
        """Write the KB to a YAML file with an informational header.

        Args:
            path: Destination path; parent directories are created.
        """
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        data = self.model_dump(mode="python", exclude_none=False)
        with p.open("w", encoding="utf-8") as fh:
            fh.write("# Jira knowledge base — generated by `parrot jiratoolkit sync-kb`.\n")
            fh.write("# Curated sections (status_map, templates, limits, priorities.legacy/default)\n")
            fh.write("# are preserved on re-sync. Inline YAML comments are NOT preserved.\n\n")
            yaml.safe_dump(data, fh, default_flow_style=False, sort_keys=False, allow_unicode=True)

    def resolve_issue_type(self, project: str, name_or_id: str) -> Optional[IssueTypeEntry]:
        """Resolve an issue type by name or id within a project."""
        proj = self.projects.get(project)
        if proj is None:
            return None
        entry = proj.issue_types.get(name_or_id)
        if entry is not None:
            return entry
        for ite in proj.issue_types.values():
            if ite.id == name_or_id:
                return ite
        return None

    def resolve_field(self, alias: str) -> str:
        """Return the Jira field id for an alias, or the alias unchanged."""
        return self.fields.get(alias, alias)

    def status_category(self, status: str) -> Optional[str]:
        """Return the category name for a status (case-insensitive), or None."""
        needle = status.strip().lower()
        for category, statuses in self.status_map.items():
            if any(s.strip().lower() == needle for s in statuses):
                return category
        return None

    def validate_limits(self, *, summary: Optional[str] = None, description: Optional[str] = None) -> None:
        """Raise ValueError if field lengths exceed KB limits."""
        max_summary = self.limits.summary_max_chars
        if summary is not None and max_summary is not None and len(summary) > max_summary:
            raise ValueError(f"summary is {len(summary)} chars; limit is {max_summary}")
        max_desc = self.limits.description_max_chars
        if description is not None and max_desc is not None and len(description) > max_desc:
            raise ValueError(f"description is {len(description)} chars; limit is {max_desc}")

    def merge_generated(self, generated: "JiraKnowledgeBase") -> "JiraKnowledgeBase":
        """Merge structural sections from ``generated`` with curated sections from ``self``.

        Structural (from ``generated``): site, cloud_id, verified, projects,
        priorities.scale, components, discovered field aliases.
        Curated (from ``self``): status_map, templates, limits,
        priorities.legacy/default, extra keys, and hand-edited field aliases
        whose ids are still known.

        Args:
            generated: Freshly generated knowledge base.

        Returns:
            A new merged knowledge base.
        """
        fields = dict(generated.fields)
        known_ids = set(generated.fields.values())
        for alias, fid in self.fields.items():
            if alias not in fields and fid in known_ids:
                fields[alias] = fid
            elif alias in fields and fields[alias] != fid and fid in known_ids:
                fields[alias] = fid
        priorities = PrioritiesEntry(
            scale=list(generated.priorities.scale),
            legacy=list(self.priorities.legacy),
            default=self.priorities.default,
        )
        data = {
            "site": generated.site,
            "cloud_id": generated.cloud_id,
            "verified": generated.verified,
            "projects": {k: v.model_dump() for k, v in generated.projects.items()},
            "priorities": priorities.model_dump(),
            "status_map": {k: list(v) for k, v in self.status_map.items()},
            "fields": fields,
            "limits": self.limits.model_dump(),
            "templates": {k: v.model_dump() for k, v in self.templates.items()},
            "components": list(generated.components),
        }
        for key, value in (self.model_extra or {}).items():
            data[key] = value
        return JiraKnowledgeBase.model_validate(data)
