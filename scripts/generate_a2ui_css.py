"""Tailwind v4 CSS Generation Script for the A2UI `interactive-html` renderer.

AST-scans `interactive_html.py`'s literal `a2ui-*`/`ds-*`/`kpi-*`/`filter-*`/
`msf-*` class-name vocabulary (FEAT-522, spec §1 gap 2 / §3 Module 4), builds
a Tailwind v4 (CSS-first, no `tailwind.config.js`/PostCSS) `@apply` rule for
each EXISTING semantic selector, runs the Tailwind CLI, and writes the
compiled CSS to `design_system/tailwind.generated.css`. Markup class names
in `interactive_html.py` are never touched — this script only writes
`@apply` rules onto selectors that already exist in the renderer's output.

Mirrors `scripts/generate_tool_registry.py`'s CLI shape and `--check`
contract exactly (same repo, same "scan source, diff, fail in CI" pattern,
confirmed at spec time to be a real, working convention — spec §2, §8).

Usage:
    python scripts/generate_a2ui_css.py              # Generate/update the CSS
    python scripts/generate_a2ui_css.py --dry-run     # Show changes without writing
    python scripts/generate_a2ui_css.py --check       # CI mode: exit 1 if stale
    python scripts/generate_a2ui_css.py --verbose      # Verbose output
"""
